const dicts: Record<Lang, Dict> = { de, en };

function initialLang(): Lang {
  if (typeof window === "undefined") return "de";
  try {
    const stored = window.localStorage.getItem("lichtwerk.lang");
    if (stored === "de" || stored === "en") return stored;
  } catch {
    /* storage may be unavailable */
  }
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

export const useLang = create<LangState>((set) => ({
  lang: "de",
  setLang: (lang) => {
    try {
      window.localStorage.setItem("lichtwerk.lang", lang);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

/** Call once on the client to pick up the stored / browser language. */
export function initLang() {
  useLang.getState().setLang(initialLang());
}

/** Translate outside React (e.g. Blockly block definitions). */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  const lang = useLang.getState().lang;
  let s: string = dicts[lang][key] ?? dicts.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Translate inside React components; re-renders on language change. */
export function useT() {
  useLang((s) => s.lang);
  return t;
}
